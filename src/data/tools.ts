// Derives the "← back to hub" pill target for any tool/calculator page from its
// href + hub membership above. Single source of truth so individual pages no
// longer hand-set backLink/backLabel. Explicit props on ToolHero still override.
export function getToolBackLink(href: string): { backLink: string; backLabel: string } {
  // Suite sub-pages → their own suite hub
  if (href.startsWith('/calculators/stem-suite/') && href !== '/calculators/stem-suite/')
    return { backLink: '/calculators/stem-suite/', backLabel: 'STEM Suite' };
  if (href.startsWith('/calculators/statistics-suite/') && href !== '/calculators/statistics-suite/')
    return { backLink: '/calculators/statistics-suite/', backLabel: 'Statistics Suite' };
  // Finance Toolkit tools (bank statement converter, money calculators, invoice
  // generator). Must come BEFORE the generic /calculators/ rule below so the
  // finance calculators route to the Finance Toolkit, not the Calculators hub.
  if (financeHrefs.has(href))
    return { backLink: '/finance-toolkit/', backLabel: 'Finance Toolkit' };
  // Any /calculators/ page (incl. the suite hub pages themselves) → Calculators hub
  if (href.startsWith('/calculators/'))
    return { backLink: '/calculators/', backLabel: 'Calculators' };
  // Developer Toolbox sub-pages
  if (href.startsWith('/developer-toolbox/'))
    return { backLink: '/developer-toolbox/', backLabel: 'Developer Toolbox' };
  // Playbooks content hub sub-pages (pillar + spokes) → Playbooks hub
  if (href.startsWith('/playbooks/') && href !== '/playbooks/')
    return { backLink: '/playbooks/', backLabel: 'Playbooks' };
  // /tools/* pages: route by which hub they belong to (order: Career, PDF, Developer, Calculators)
  if (careerTools.some(t => t.href === href)) return { backLink: '/career-toolkit/', backLabel: 'Career Toolkit' };
  if (pdfTools.some(t => t.href === href)) return { backLink: '/pdf-toolkit/', backLabel: 'PDF Toolkit' };
  if (developerTools.some(t => t.href === href)) return { backLink: '/developer-toolbox/', backLabel: 'Developer Toolbox' };
  if (calculatorTools.some(t => t.href === href)) return { backLink: '/calculators/', backLabel: 'Calculators' };
  // Default → global tools index
  return { backLink: '/tools/', backLabel: 'All Tools' };
}

